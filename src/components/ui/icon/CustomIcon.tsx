type ICustomIconProps = {
  name: keyof typeof icons;
  color?: string;
  size?: number;
  className?: string;
  fill?: string;
  stroke?: string;
  caption?: string;
  tooltip?: string;
  onClick?: () => void;
};

const CustomIcon: React.FC<ICustomIconProps> = ({
  name,
  color = 'currentColor',
  size = 24,
  tooltip = '',
  fill,
  stroke,
  className,
  caption,
  onClick,
}) => {
  const icon = icons[name];

  const [showTooltip, setShowTooltip] = useState(false);
  const iconRef = useRef<HTMLDivElement>(null);

  const getViewBox = () => {
    switch (name) {
      case 'arrow-left':
        return '0 0 22 16';
      case 'arrow-right':
        return '0 0 22 16';
      case 'cross':
        return `0 0 ${size} ${size}`;
      case 'login':
        return '0 0 32 32';
      case 'user':
        return '0 0 16 16';
      case 'password':
        return '0 0 18 24';
      // return '0 0 44 48';
      case 'youtube':
      case 'email':
      case 'check':
      case 'refresh':
      case 'warning':
        return '0 0 24 24';
      case 'eye-opened':
      case 'eye-closed':
        return '0 0 32 32';
      case 'open-password':
        return '0 0 14 21';
      default:
        return `0 0 ${size} ${size}`;
    }
  };

  if (!icon) {
    return null;
  }

  return (
    <div
      className={'relative flex flex-col items-center justify-center ' + className}
      onMouseEnter={() => setShowTooltip(true)}
      onMouseLeave={() => setShowTooltip(false)}
      onClick={onClick}
      ref={iconRef}
    >
      <svg
        width={size}
        height={size}
        viewBox={getViewBox()}
        fill={'none'}
      >
        {React.cloneElement(icon, {
          fill: fill || color,
          stroke: stroke || color,
          width: '100%',
          height: '100%',
        })}
      </svg>
      {tooltip && showTooltip && (
        <div
          className={`absolute w-max top-[${size}px] right-[10px] px-3 py-1 mobile:text-sm desktop:text-xl text-white bg-black rounded-md`}
        >
          {tooltip}
        </div>
      )}
      {caption ? <div className={'text-xl text-white'}>{caption}</div> : null}
    </div>
  );
};

export default CustomIcon;
