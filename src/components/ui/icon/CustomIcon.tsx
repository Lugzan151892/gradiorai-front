type ICustomIconProps = {
  name: keyof typeof icons;
  color?: string;
  size?: number;
  className?: string;
  fill?: string;
  stroke?: string;
  caption?: string;
  tooltip?: string;
  onClick?: () => void;
};

const CustomIcon: React.FC<ICustomIconProps> = ({
  name,
  color = 'var(--main-gray)',
  size = 24,
  tooltip = '',
  className,
  caption,
  onClick,
}) => {
  const icon = icons[name];

  const [showTooltip, setShowTooltip] = useState(false);
  const iconRef = useRef<HTMLDivElement>(null);

  const getViewBox = () => {
    switch (name) {
      case 'arrow-left':
        return '0 0 22 16';
      case 'arrow-right':
        return '0 0 22 16';
      case 'cross':
        return `0 0 ${size} ${size}`;
      case 'login':
        return '0 0 32 32';
      case 'user':
        return '0 0 16 16';
      case 'password':
      case 'youtube':
      case 'email':
      case 'check':
      case 'refresh':
      case 'warning':
      case 'eye-opened':
      case 'eye-closed':
        return '0 0 24 24';
      case 'open-password':
        return '0 0 14 21';
      default:
        return `0 0 ${size} ${size}`;
    }
  };

  if (!icon) {
    return null;
  }

  return (
    <div
      className={'relative flex flex-col items-center justify-center ' + className}
      onMouseEnter={() => setShowTooltip(true)}
      onMouseLeave={() => setShowTooltip(false)}
      onClick={onClick}
      ref={iconRef}
    >
      <svg
        width={size}
        height={size}
        viewBox={getViewBox()}
        style={{ color }}
      >
        {icon}
      </svg>
      {tooltip && showTooltip && (
        <div
          className={`absolute w-max top-[${size}px] right-[10px] px-3 py-1 mobile:text-sm desktop:text-xl text-white bg-black rounded-md`}
        >
          {tooltip}
        </div>
      )}
      {caption ? <div className={'desktop:text-xl mobile:text-sm text-white'}>{caption}</div> : null}
    </div>
  );
};

export default CustomIcon;
